import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const artifactDir = path.join(root, 'test-results')
await fs.mkdir(artifactDir, { recursive: true })
const executablePath = process.env.PLAYWRIGHT_BROWSER_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const browser = await chromium.launch({ executablePath, headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1024 }, acceptDownloads: true })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const results = []
async function check(name, fn) {
  await fn(); results.push(name); console.log(`PASS ${name}`)
}
async function screenshot(name) {
  await page.evaluate(() => { window.scrollTo(0, 0); if (document.activeElement instanceof HTMLElement) document.activeElement.blur() })
  await page.screenshot({ path: path.join(artifactDir, `${name}.png`), fullPage: true })
}
try {
  await page.goto('http://127.0.0.1:5173/#/projects', { waitUntil: 'networkidle' })
  await check('Projects: reference-inspired layout, search and sector filters', async () => {
    assert.equal(await page.locator('.project-card').count(), 4)
    await screenshot('projects-desktop')
    await page.getByLabel('Search projects').fill('enfuce')
    assert.equal(await page.locator('.project-card').count(), 2)
    await page.getByLabel('Search projects').fill('')
    await page.getByLabel('Filter projects by sector').selectOption('Crowdfunding')
    assert.equal(await page.locator('.project-card').count(), 1)
    await page.getByLabel('Filter projects by sector').selectOption('All sectors')
  })
  await check('Dashboard: real monthly figures and source values', async () => {
    await page.getByRole('link', { name: 'Open Enfuce dashboard', exact: true }).click()
    await page.getByRole('heading', { name: 'Data dashboard' }).waitFor()
    assert.match(await page.locator('.hero-number').innerText(), /3,417,663.76/)
    await page.getByRole('button', { name: 'View data', exact: true }).click()
    assert.match(await page.locator('.source-table').innerText(), /574,214.88/)
    await page.getByRole('button', { name: 'Hide table', exact: true }).click()
    await screenshot('dashboard-desktop')
    await page.getByRole('button', { name: 'Operating income', exact: true }).click()
    assert.match(await page.locator('.hero-number').innerText(), /3,452,682.81/)
  })
  await check('Metric detail: graph, node selection, zoom, evidence inspector', async () => {
    await page.locator('.metric-card').filter({ hasText: '2019 gross profit' }).click()
    const dialog = page.getByRole('dialog', { name: '2019 gross profit', exact: true })
    await dialog.waitFor()
    await dialog.getByRole('button', { name: 'Zoom in', exact: true }).click()
    assert.match(await dialog.locator('.lineage-toolbar').innerText(), /110%/)
    await dialog.locator('.lineage-node.formula').click()
    assert.match(await dialog.locator('.lineage-selection').innerText(), /5,095.50635/)
    await screenshot('lineage-desktop')
    await dialog.getByRole('button', { name: 'Open evidence inspector', exact: true }).click()
    await page.getByRole('dialog', { name: 'Evidence inspector' }).waitFor()
    assert.match(await page.locator('.source-table').innerText(), /50 kEUR/)
    await page.keyboard.press('Escape')
  })
  await check('Report Builder: configuration, module selection, reorder and persistence', async () => {
    await page.getByRole('link', { name: 'Report', exact: true }).click()
    await page.getByRole('heading', { name: 'Make it your report.' }).waitFor()
    await page.getByRole('button', { name: 'Deep', exact: true }).click()
    await page.getByRole('combobox', { name: /^Geography/ }).selectOption('US')
    await page.getByRole('radio', { name: 'Internal + external', exact: true }).check()
    await page.getByLabel('Additional focus', { exact: false }).fill('Focus on Gen Z purchasing behavior')
    await page.getByRole('button', { name: 'Add Product', exact: true }).click()
    assert.equal(await page.locator('.structure-item').count(), 7)
    await page.getByRole('button', { name: 'Move Product up', exact: true }).click()
    assert.match(await page.locator('.structure-item').nth(5).innerText(), /Product/)
    await page.getByRole('button', { name: 'Remove Product', exact: true }).click()
    await page.locator('.structure-item').nth(0).dragTo(page.locator('.structure-item').nth(2))
    assert.match(await page.locator('.structure-item').nth(2).innerText(), /Company overview/)
    await page.locator('.structure-item').nth(2).dragTo(page.locator('.structure-item').nth(0))
    await page.getByRole('button', { name: 'Customize Market', exact: true }).click()
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await page.getByRole('button', { name: 'Deep', exact: true }).getAttribute('aria-pressed'), 'true')
    assert.equal(await page.getByRole('combobox', { name: /^Geography/ }).inputValue(), 'US')
    await screenshot('report-build-desktop')
  })
  await check('Report review: linked claims, human edits and revision activity', async () => {
    await page.getByRole('button', { name: 'Generate report preview', exact: false }).click()
    await page.locator('.report-paper').waitFor()
    assert.match(await page.locator('#section-market').innerText(), /No supporting evidence/)
    assert.match(await page.locator('#section-market').innerText(), /Gen Z/)
    await page.locator('#section-financials').getByRole('button', { name: 'Inspect H1 2020 operating income evidence', exact: true }).click()
    await page.getByRole('dialog', { name: 'Evidence inspector' }).waitFor()
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Edit Company overview', exact: true }).click()
    const editor = page.getByLabel('Section content', { exact: true })
    await editor.fill(`${await editor.inputValue()}\n\nReviewer note: confirm consolidation scope.`)
    await page.getByRole('button', { name: 'Save revision', exact: true }).click()
    assert.match(await page.locator('.activity-events').innerText(), /Revised Company overview/)
    await screenshot('report-review-desktop')
    await page.getByRole('button', { name: 'Version history', exact: false }).click()
    assert.match(await page.getByRole('dialog', { name: 'Revision history' }).innerText(), /Company overview/)
    await page.keyboard.press('Escape')
  })
  await check('Export: actual Markdown, PDF and DOCX downloads', async () => {
    await page.getByRole('button', { name: 'Continue to export', exact: true }).click()
    for (const format of ['Markdown', 'PDF', 'DOCX']) {
      await page.locator('.format-options').getByRole('button', { name: new RegExp(`^${format}`) }).click()
      const waiting = page.waitForEvent('download')
      await page.getByRole('button', { name: `Download ${format}`, exact: true }).click()
      const download = await waiting
      const filePath = path.join(artifactDir, download.suggestedFilename())
      await download.saveAs(filePath)
      const bytes = await fs.readFile(filePath)
      assert.ok(bytes.length > 500)
      if (format === 'PDF') assert.equal(bytes.subarray(0, 4).toString(), '%PDF')
      if (format === 'DOCX') assert.equal(bytes.subarray(0, 2).toString(), 'PK')
      if (format === 'Markdown') assert.match(bytes.toString(), /Reviewer note: confirm consolidation scope/)
    }
    await screenshot('report-export-desktop')
  })
  await check('Data room: upload, persisted text source viewer and external URL validation', async () => {
    await page.getByRole('link', { name: 'Data room', exact: true }).click()
    await page.getByLabel('Upload source files', { exact: true }).setInputFiles({ name: 'review-notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Source review note: check the revenue definition.') })
    await page.locator('.source-name').filter({ hasText: 'review-notes.txt' }).waitFor()
    await page.reload({ waitUntil: 'networkidle' })
    await page.locator('.source-name').filter({ hasText: 'review-notes.txt' }).click()
    assert.match(await page.getByRole('dialog', { name: 'review-notes.txt', exact: true }).innerText(), /check the revenue definition/)
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Add source link', exact: true }).click()
    await page.getByLabel('Source name', { exact: true }).fill('Industry source')
    await page.getByLabel('URL', { exact: true }).fill('javascript:alert(1)')
    await page.getByRole('button', { name: 'Save source', exact: true }).click()
    await page.getByText('Enter a valid https:// or http:// address.', { exact: true }).waitFor()
    await page.getByLabel('URL', { exact: true }).fill('https://example.com/research')
    await page.getByRole('button', { name: 'Save source', exact: true }).click()
    await page.locator('.source-name').filter({ hasText: 'Industry source' }).waitFor()
    await screenshot('data-room-desktop')
  })
  await check('Contextual chat: source-backed response and open evidence', async () => {
    await page.getByRole('button', { name: 'Ask anything about your evidence', exact: true }).click()
    await page.getByRole('button', { name: 'Explain the €50k gross profit adjustment', exact: false }).click()
    assert.match(await page.locator('.chat-messages').innerText(), /no documented business explanation/)
    await page.locator('.message-sources').getByRole('button', { name: '2019 gross profit', exact: true }).click()
    await page.getByRole('dialog', { name: 'Evidence inspector' }).waitFor()
    await page.keyboard.press('Escape')
  })
  await check('Project creation and data isolation', async () => {
    await page.getByRole('button', { name: 'Project', exact: true }).click()
    await page.getByLabel('Project name', { exact: true }).fill('New test project')
    await page.getByRole('button', { name: 'Create project', exact: true }).click()
    await page.getByRole('button', { name: 'Generate report preview', exact: false }).click()
    await page.locator('.report-paper').waitFor()
    assert.doesNotMatch(await page.locator('.report-paper').innerText(), /3,452,682|16 customers/)
    assert.match(await page.locator('.report-paper').innerText(), /No supporting evidence/)
  })
  await check('Mobile: no page overflow and usable navigation', async () => {
    await page.setViewportSize({ width: 390, height: 844 })
    for (const route of ['/projects', '/project/enfuce/report/build', '/project/enfuce/report/review', '/project/enfuce/dashboard', '/project/enfuce/data-room']) {
      await page.goto(`http://127.0.0.1:5173/#${route}`, { waitUntil: 'networkidle' })
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
      assert.equal(overflow, false, `Horizontal overflow at ${route}`)
      await screenshot(`mobile-${route.split('/').filter(Boolean).slice(-1)[0]}`)
    }
    await page.getByRole('button', { name: 'Toggle navigation', exact: true }).click()
    await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
    await page.getByRole('heading', { name: 'Data dashboard', exact: true }).waitFor()
  })
  assert.deepEqual(errors, [], 'Browser runtime errors')
  await fs.writeFile(path.join(artifactDir, 'results.json'), JSON.stringify({ passed: results, errors }, null, 2))
  console.log(`Verified ${results.length} end-to-end flows; no browser errors.`)
} catch (error) {
  await screenshot('failure')
  throw error
} finally { await browser.close() }
